#!/usr/bin/env node
// Generates the acme/payments demo runs in demo/runs/: 22 CI runs that walk tests through every path of the
// status lifecycle (ADR-0007). Deterministic, so the committed files only change when this script does.
//
//   node scripts/generate-demo-runs.mjs
//
// The story, per test (P = passed, F = failed, E = error, R = passed after a failed Surefire rerun):
//   refundsPartially   keeps flipping between pass and fail -> suspicious, then flaky by flip rate
//   capturesPayment    a regression on four commits, then fixed -> stays stable: broken, not flaky
//   reconcilesLedger   error and pass on one commit, then a rerun pass -> flaky; ten clean passes -> recovered
//   authorizesCard     fails and passes on one re-run commit -> suspicious, not yet recovered
//   others             always pass
// analysis-service's DemoRunsTest replays these files and checks that the story still holds.

import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const RUNS_DIR = path.resolve(import.meta.dirname, '../demo/runs');
const REPOSITORY = 'acme/payments';
const FIRST_DIR_NUMBER = 5;

// [commit index, attempt, story note]; a commit index repeated with attempt 2 is a CI re-run of that commit.
const RUNS = [
  [1, 1, 'reconcilesLedger errors'],
  [1, 2, 're-run of the same commit: reconcilesLedger passes -> suspicious'],
  [2, 1, 'reconcilesLedger passes only after a Surefire rerun -> flaky'],
  [3, 1, ''],
  [4, 1, 'refundsPartially has flipped three times -> suspicious'],
  [5, 1, ''],
  [6, 1, ''],
  [7, 1, ''],
  [8, 1, ''],
  [9, 1, 'refundsPartially flips again -> flaky by flip rate'],
  [10, 1, ''],
  [11, 1, ''],
  [12, 1, 'tenth clean pass of reconcilesLedger -> recovered'],
  [13, 1, 'capturesPayment regresses'],
  [14, 1, 'authorizesCard fails'],
  [14, 2, 're-run of the same commit: authorizesCard passes -> suspicious'],
  [15, 1, ''],
  [16, 1, 'capturesPayment is fixed'],
  [17, 1, ''],
  [18, 1, ''],
  [19, 1, ''],
  [20, 1, ''],
];

// One outcome per run, in the order of RUNS.
const STORIES = {
  refundsPartially: 'PPFPFPPFPFPPFPPPFPPFPP',
  capturesPayment: 'PPPPPPPPPPPPPFFFFPPPPP',
  reconcilesLedger: 'EPRPPPPPPPPPPPPPPPPPPP',
  authorizesCard: 'PPPPPPPPPPPPPPFPPPPPPP',
};

const CLASSES = {
  'io.example.payments.PaymentServiceTest': ['authorizesCard', 'capturesPayment', 'refundsPartially', 'formatsAmount'],
  'io.example.payments.LedgerTest': ['reconcilesLedger', 'validatesIban'],
};

const FAILURES = {
  refundsPartially: ['expected refund of 12.50 but was 0.00', 'org.opentest4j.AssertionFailedError'],
  capturesPayment: ['expected status CAPTURED but was PENDING', 'org.opentest4j.AssertionFailedError'],
  reconcilesLedger: ['Connection refused: ledger-db:5432', 'java.net.ConnectException'],
  authorizesCard: ['Read timed out after 2000 ms', 'java.net.SocketTimeoutException'],
};

function sha(commit) {
  // 40 hex characters; the commit number sits in the first seven, which is what the dashboard shows: c001ffe, c002ffe
  return `c0${String(commit).padStart(2, '0')}ffee`.padEnd(40, '0');
}

function outcome(test, runIndex) {
  return STORIES[test]?.[runIndex] ?? 'P';
}

function escape(text) {
  return text.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('"', '&quot;');
}

function testcase(className, test, result, index) {
  const time = (0.01 + ((index * 37) % 50) / 1000).toFixed(3);
  const open = `  <testcase name="${test}" classname="${className}" time="${time}"`;
  if (result === 'P') {
    return `${open}/>`;
  }
  const [message, type] = FAILURES[test] ?? ['failed', 'java.lang.AssertionError'];
  const element = { F: 'failure', E: 'error', R: 'flakyFailure' }[result];
  return [
    `${open}>`,
    `    <${element} message="${escape(message)}" type="${type}">`,
    `      <stackTrace>${escape(`${type}: ${message}`)}</stackTrace>`,
    `    </${element}>`,
    '  </testcase>',
  ].join('\n');
}

function report(className, tests, runIndex) {
  const results = tests.map((test) => outcome(test, runIndex));
  const failures = results.filter((r) => r === 'F').length;
  const errors = results.filter((r) => r === 'E').length;
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    `<testsuite name="${className}" tests="${tests.length}" failures="${failures}" errors="${errors}" skipped="0">`,
    ...tests.map((test, i) => testcase(className, test, results[i] ?? 'P', runIndex + i)),
    '</testsuite>',
    '',
  ].join('\n');
}

RUNS.forEach(([commit, attempt, note], runIndex) => {
  const number = String(FIRST_DIR_NUMBER + runIndex).padStart(2, '0');
  const dir = path.join(RUNS_DIR, `${number}-payments-run-${String(runIndex + 1).padStart(2, '0')}`);
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  const env = [
    `# Generated by scripts/generate-demo-runs.mjs${note ? `: ${note}` : ''}`,
    `REPOSITORY=${REPOSITORY}`,
    `COMMIT_SHA=${sha(commit)}`,
    'BRANCH=main',
    `EXTERNAL_RUN_ID=${3000 + commit}`,
    `ATTEMPT=${attempt}`,
    '',
  ].join('\n');
  writeFileSync(path.join(dir, 'run.env'), env);
  for (const [className, tests] of Object.entries(CLASSES)) {
    writeFileSync(path.join(dir, `TEST-${className}.xml`), report(className, tests, runIndex));
  }
});

console.log(`Wrote ${RUNS.length} runs of ${REPOSITORY} to ${path.relative(process.cwd(), RUNS_DIR)}`);
